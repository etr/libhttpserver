constexpr const qpack_static_entry* qpack_static_lookup(std::uint64_t index) noexcept {
    return index < qpack_static_entries.size() ? &qpack_static_entries[index] : nullptr;
}
constexpr std::optional<std::uint64_t> qpack_static_find_name(std::string_view name) noexcept {
    for (std::size_t i = 0; i < qpack_static_entries.size(); ++i) {
        if (qpack_static_entries[i].name == name) return i;
    }
    return std::nullopt;
}
constexpr std::optional<std::uint64_t> qpack_static_find(std::string_view name, std::string_view value) noexcept {
    for (std::size_t i = 0; i < qpack_static_entries.size(); ++i) {
        if (qpack_static_entries[i].name == name && qpack_static_entries[i].value == value) return i;
    }
    return std::nullopt;
}
